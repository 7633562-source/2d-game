using UnityEngine;

// Слой намерения: чего человек хочет, а не как он этого добивается.
// Компонент хранит только числа и не содержит логики. Заполнять их может
// кто угодно: PlayerInputSource с клавиатуры, безоконный стенд программно,
// позже — ИИ существа.
//
// Ввод сознательно не читается балансировщиком напрямую. Во-первых, у стенда
// без окна клавиатуры нет, и прогон пришлось бы обкладывать условной
// компиляцией. Во-вторых, при сотне существ клавиатуру должен опрашивать
// один — тот, которым играют, — а не каждый в своём FixedUpdate.
//
// Здесь лежит цель, а не сглаженная величина: crouch с клавиатуры принимает
// только 0 или 1. Плавный переход в позу делает управляющий слой, иначе стенд,
// выставляющий crouch = 1 напрямую, получил бы мгновенный присед и повёл бы
// себя иначе, чем то же нажатие клавиши.
public class MotionIntent : MonoBehaviour
{
    [Header("Направление движения: -1 назад, +1 вперёд, 0 стоять")]
    [Range(-1f, 1f)]
    public float moveX;

    [Header("Цель приседания: 0 стоя, 1 на корточках")]
    [Range(0f, 1f)]
    public float crouch;
}
